import { Suspense } from "react";
import { Ocean } from "@/components/Ocean";
import { RoadmapFlow } from "@/components/RoadmapFlow";
import { api } from "@/lib/api";

async function RoadmapContent({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const roadmap = await api.roadmap(slug);
  return (
    <>
      <h1 className="text-3xl font-bold">{roadmap.career}</h1>
      <p className="mt-2 max-w-3xl opacity-85">{roadmap.summary}</p>
      <p className="mt-1 text-xs opacity-60">Generated by: {roadmap.generated_by}</p>
      <div className="mt-6">
        <RoadmapFlow steps={roadmap.steps} />
      </div>
    </>
  );
}

export default function RoadmapPage({ params }: PageProps<"/roadmap/[slug]">) {
  return (
    <Ocean depth={0.7}>
      <main className="mx-auto max-w-6xl px-6 pt-24 pb-16">
        <p className="text-sm uppercase tracking-wide opacity-70">Your pathway</p>
        <Suspense fallback={<p className="mt-2 opacity-70">Charting your dive…</p>}>
          <RoadmapContent params={params} />
        </Suspense>
      </main>
    </Ocean>
  );
}
