"use client";

import Link from "next/link";
import { useEffect, useState } from "react";
import { RoadmapFlow } from "@/components/RoadmapFlow";
import { AccountError, goToLogin, me, type SavedRoadmap } from "@/lib/api";

const dateFmt = new Intl.DateTimeFormat("en-US", { month: "long", day: "numeric", year: "numeric" });

/** One saved roadmap, exactly as it was when the student saved it. */
export function SavedRoadmapView({ id }: { id: number }) {
  const [saved, setSaved] = useState<SavedRoadmap | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    me.roadmap(id)
      .then(setSaved)
      .catch((e) => {
        if (e instanceof AccountError && e.status === 401) {
          goToLogin(`/account/roadmaps/${id}`);
          return;
        }
        setError(e instanceof AccountError && e.status === 404 ? "That roadmap isn't in your account." : "Couldn't load this roadmap.");
      });
  }, [id]);

  if (error) {
    return (
      <div>
        <p className="rounded bg-red-500/80 p-3 text-sm">{error}</p>
        <Link href="/account" className="mt-4 inline-block font-mono text-[11px] tracking-[0.16em] uppercase hover:underline">
          ← My roadmaps
        </Link>
      </div>
    );
  }
  if (!saved) return <p className="mt-2 opacity-70">Charting your dive…</p>;

  const { roadmap } = saved;
  return (
    <>
      <h1 className="text-3xl font-bold">{roadmap.career}</h1>
      <p className="mt-2 max-w-3xl opacity-85">{roadmap.summary}</p>
      <p className="mt-1 text-xs opacity-60">
        Saved {dateFmt.format(new Date(saved.updated_at))} · Generated by: {roadmap.generated_by}
      </p>
      <div className="mt-5 flex flex-wrap gap-3">
        <Link
          href="/account"
          className="border border-white/30 px-5 py-2.5 font-mono text-xs tracking-[0.16em] text-white uppercase transition hover:bg-white/10"
        >
          ← My roadmaps
        </Link>
        <Link
          href={`/roadmap/${saved.major_slug}`}
          className="border border-white/30 px-5 py-2.5 font-mono text-xs tracking-[0.16em] text-white uppercase transition hover:bg-white/10"
        >
          See latest version
        </Link>
      </div>
      <div className="mt-6">
        <RoadmapFlow steps={roadmap.steps} />
      </div>
    </>
  );
}
